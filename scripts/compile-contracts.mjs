import solc from "solc";
import fs from "node:fs";
import path from "node:path";

const ROOT = "/dev-server";
function findImport(p) {
  const candidates = [
    path.join(ROOT, "node_modules", p),
    path.join(ROOT, "contracts", p),
  ];
  for (const c of candidates) {
    if (fs.existsSync(c)) return { contents: fs.readFileSync(c, "utf8") };
  }
  return { error: "Not found: " + p };
}

const sources = {};
for (const f of ["PortfolioVerification.sol", "PortfolioOwnership.sol"]) {
  sources[f] = { content: fs.readFileSync(path.join(ROOT, "contracts", f), "utf8") };
}

const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    viaIR: true,
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const out = JSON.parse(solc.compile(JSON.stringify(input), { import: findImport }));
const errs = (out.errors || []).filter((e) => e.severity === "error");
if (errs.length) { console.error(errs.map((e) => e.formattedMessage).join("\n")); process.exit(1); }
for (const w of (out.errors || [])) console.log("[warn]", w.formattedMessage?.split("\n")[0]);

const pick = (file, name) => {
  const c = out.contracts[file][name];
  return { abi: c.abi, bytecode: "0x" + c.evm.bytecode.object };
};
const verification = pick("PortfolioVerification.sol", "PortfolioVerification");
const ownership = pick("PortfolioOwnership.sol", "PortfolioOwnership");

const banner = `// AUTO-GENERATED by contracts compilation (solc ${solc.version()}, optimizer runs=200, viaIR).\n// Source: contracts/PortfolioVerification.sol, contracts/PortfolioOwnership.sol\n// Do not edit by hand.\n`;
const body = `${banner}
export const VERIFICATION_ABI = ${JSON.stringify(verification.abi)} as const;

export const VERIFICATION_BYTECODE = "${verification.bytecode}" as \`0x\${string}\`;

export const OWNERSHIP_ABI = ${JSON.stringify(ownership.abi)} as const;

export const OWNERSHIP_BYTECODE = "${ownership.bytecode}" as \`0x\${string}\`;
`;
fs.mkdirSync(path.join(ROOT, "src/lib/blockchain"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "src/lib/blockchain/artifacts.ts"), body);
console.log("OK bytecode sizes:", verification.bytecode.length / 2, ownership.bytecode.length / 2);
